// Как показывать код скидочной карты: штрихкодом, QR-кодом или просто
// цифрами.
//
// Отдельный модуль ради ОДНОЙ функции — потому что это правило совместимости,
// а не украшение. Раньше режим хранился булевым `barcode`, и данные с таким
// полем уже лежат у пользователей и синхронизируются между устройствами. У
// части устройств может стоять сборка, которая про QR ещё не знает.

import type { BankCard } from '../types'

export type CardCodeView = 'barcode' | 'qr' | 'none'

/**
 * Режим показа кода. Читает новое поле, а при его отсутствии выводит режим
 * из старого булева — так карты, заведённые до появления QR (и пришедшие с
 * устройства на старой сборке), продолжают показываться как раньше.
 */
export function cardCodeView(card: Pick<BankCard, 'codeView' | 'barcode'>): CardCodeView {
  if (card.codeView) return card.codeView
  // историческое значение: отсутствие поля означало «штрихкод»
  return card.barcode === false ? 'none' : 'barcode'
}

/**
 * Поля для записи в карту. Пишем ОБА: старое булево нужно, чтобы карта,
 * уехавшая в облако и открытая на устройстве со старой сборкой, показалась
 * осмысленно — штрихкодом или цифрами, но не сломанной.
 *
 * QR там выродится в штрихкод. Это осознанный компромисс: показать не тот
 * тип кода лучше, чем показать пустоту, а номер под кодом одинаковый.
 */
export function cardCodeFields(view: CardCodeView): { codeView: CardCodeView; barcode: boolean } {
  return { codeView: view, barcode: view !== 'none' }
}
